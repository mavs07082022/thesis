import { useState, useEffect } from 'react';
import { History as HistoryIcon, Search, Calendar } from 'lucide-react';
import Card from '@/components/common/Card';
import Loader from '@/components/common/Loader';
import EmptyState from '@/components/common/EmptyState';
import Badge from '@/components/common/Badge';
import { predictionService } from '@/services/predictionService';
import { PredictionResult } from '@/types';
import { formatDateTime } from '@/utils/formatters';
import { SUITABILITY_COLORS } from '@/utils/constants';
import clsx from 'clsx';

export default function History() {
  const [items, setItems] = useState<PredictionResult[]>([]);
  const [loading, setLoading] = useState(true);
  const [query, setQuery] = useState('');
  const [expanded, setExpanded] = useState<string | null>(null);

  useEffect(() => {
    predictionService
      .getHistory()
      .then(setItems)
      .finally(() => setLoading(false));
  }, []);

  const filtered = items.filter((i) =>
    i.id.toLowerCase().includes(query.toLowerCase())
  );

  return (
    <div className="space-y-6">
      <div className="flex items-start justify-between flex-wrap gap-3">
        <div>
          <h1 className="text-2xl font-bold text-slate-800">Prediction History</h1>
          <p className="text-sm text-slate-500 mt-1">
            Past crop suitability predictions generated by the system.
          </p>
        </div>
      </div>

      <Card>
        <div className="flex items-center gap-2 mb-4">
          <Search className="w-4 h-4 text-slate-400" />
          <input
            type="text"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search by prediction ID..."
            className="flex-1 bg-transparent text-sm text-slate-700 placeholder:text-slate-400 focus:outline-none"
          />
        </div>

        {loading ? (
          <Loader />
        ) : filtered.length === 0 ? (
          <EmptyState
            icon={<HistoryIcon className="w-12 h-12" />}
            title="No predictions found"
            description="Prediction history will appear here once the system generates results."
          />
        ) : (
          <div className="space-y-2">
            {filtered.map((item) => {
              const top = item.predictions[0];
              const isOpen = expanded === item.id;
              return (
                <div
                  key={item.id}
                  className="border border-slate-200 rounded-lg overflow-hidden transition-all hover:border-primary-300"
                >
                  <button
                    onClick={() => setExpanded(isOpen ? null : item.id)}
                    className="w-full flex items-center justify-between gap-3 p-4 text-left hover:bg-slate-50 transition-colors"
                  >
                    <div className="flex items-center gap-3 min-w-0">
                      <div className="w-9 h-9 rounded-lg bg-primary-50 flex items-center justify-center flex-shrink-0">
                        <Calendar className="w-4 h-4 text-primary-600" />
                      </div>
                      <div className="min-w-0">
                        <p className="text-sm font-semibold text-slate-800">{item.id}</p>
                        <p className="text-xs text-slate-500 truncate">
                          {formatDateTime(item.timestamp)}
                        </p>
                      </div>
                    </div>
                    <div className="flex items-center gap-3 flex-shrink-0">
                      <div className="hidden sm:block text-right">
                        <p className="text-[10px] uppercase tracking-wide text-slate-500">
                          Top Crop
                        </p>
                        <p className="text-xs font-semibold text-slate-700">{top.cropName}</p>
                      </div>
                      <span className={clsx('badge', SUITABILITY_COLORS[top.suitability])}>
                        {top.score.toFixed(0)}%
                      </span>
                    </div>
                  </button>

                  {isOpen && (
                    <div className="border-t border-slate-200 bg-slate-50 p-4">
                      <div className="grid grid-cols-2 sm:grid-cols-5 gap-3 mb-4">
                        <InputItem label="Soil pH" value={item.inputConditions.soilPh} />
                        <InputItem
                          label="Moisture"
                          value={`${item.inputConditions.soilMoisture}%`}
                        />
                        <InputItem
                          label="Temp"
                          value={`${item.inputConditions.temperature}°C`}
                        />
                        <InputItem
                          label="Humidity"
                          value={`${item.inputConditions.humidity}%`}
                        />
                        <InputItem
                          label="Rainfall"
                          value={`${item.inputConditions.rainfall}mm`}
                        />
                      </div>
                      <div className="space-y-1.5">
                        {item.predictions.map((p) => (
                          <div
                            key={p.cropId}
                            className="flex items-center justify-between text-xs bg-white rounded-md px-3 py-2 border border-slate-200"
                          >
                            <span className="font-medium text-slate-700">{p.cropName}</span>
                            <div className="flex items-center gap-2">
                              <Badge
                                variant={
                                  p.suitability === 'Suitable'
                                    ? 'success'
                                    : p.suitability === 'Moderately Suitable'
                                    ? 'warning'
                                    : 'danger'
                                }
                              >
                                {p.suitability}
                              </Badge>
                              <span className="font-semibold text-slate-700 min-w-[36px] text-right">
                                {p.score.toFixed(0)}%
                              </span>
                            </div>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        )}
      </Card>
    </div>
  );
}

function InputItem({ label, value }: { label: string; value: string | number }) {
  return (
    <div>
      <p className="text-[10px] uppercase tracking-wide font-semibold text-slate-500">
        {label}
      </p>
      <p className="text-sm font-semibold text-slate-800 mt-0.5">{value}</p>
    </div>
  );
}